# ── NMU010 ──────────────────────────────────────────────────────────────────

_SO_VALID_SUFFIXES = ("_Data", "_Config", "_Settings", "_Definition", "_Parameters")


def detect_unity_scriptableobject_suffix(records: List[AssetRecord]) -> List[Issue]:
    """ScriptableObject asset lacks a descriptive suffix (_Data, _Config, _Settings).

    ScriptableObjects serve as data containers and configuration holders.
    A suffix that describes their role (_Data, _Config, _Settings) makes
    their purpose immediately clear and avoids confusion with other asset
    types in the same folder.
    """
    issues: List[Issue] = []
    for record in records:
        type_name = (record.get("asset_type") or "").strip()
        if type_name != "ScriptableObject":
            continue
        asset_name = _name_of(record.get("asset_path", ""))
        if not asset_name:
            continue
        if any(asset_name.endswith(suffix) for suffix in _SO_VALID_SUFFIXES):
            continue
        suffix_list = ", ".join(f"`{suffix}`" for suffix in _SO_VALID_SUFFIXES[:3])
        issues.append(
            _emit(
                "NMU010",
                record["asset_path"],
                type_name,
                f"ScriptableObject `{asset_name}` should end with {suffix_list}, etc.",
                fix_suggestion=f"{asset_name}_Data",
            )
        )
    return issues


