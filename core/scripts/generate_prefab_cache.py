def main() -> int:
    rule_meta = {
        rid: {
            "rule_name": RULE_NAMES[rid],
            "rule_explanation": _get_explanations().get(rid, ""),
        }
        for rid in RULE_NAMES
    }

    # Sanity: every rule must have exactly two prefab examples.
    missing = [r for r in RULE_NAMES if r not in PREFAB_EXAMPLES]
    extras = [r for r in PREFAB_EXAMPLES if r not in RULE_NAMES]
    if missing or extras:
        print(f"FATAL: prefab coverage mismatch. missing={missing} extras={extras}")
        return 1
    for rid, samples in PREFAB_EXAMPLES.items():
        if len(samples) != 2:
            print(f"FATAL: {rid} has {len(samples)} examples (expected 2)")
            return 1

    created_at = datetime.now(timezone.utc).isoformat()

    entries: list[dict] = []
    for rid in sorted(RULE_NAMES):
        for i, sample in enumerate(PREFAB_EXAMPLES[rid], start=1):
            entries.append(
                {
                    "rule_id": rid,
                    "rule_name": rule_meta[rid]["rule_name"],
                    "example_num": i,
                    "complexity": COMPLEXITY.get(rid, "moderate"),
                    "domain": (
                        "naming"
                        if rid.startswith("NM")
                        else ("blueprint" if rid.startswith("BP") else "cpp")
                    ),
                    "snippet": sample["snippet"],
                    "explanation": sample["explanation"],
                    "generated_with": "claude-opus-4-7",
                    "created_at": created_at,
                }
            )

    output_path = (
        Path(__file__).resolve().parent.parent.parent
        / "data"
        / ("prefabricated_explanations.json")
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(entries, f, indent=2, ensure_ascii=False)

    # Summary stats
    counts_by_complexity: dict[str, int] = {}
    counts_by_domain: dict[str, int] = {}
    for e in entries:
        counts_by_complexity[e["complexity"]] = (
            counts_by_complexity.get(e["complexity"], 0) + 1
        )
        counts_by_domain[e["domain"]] = counts_by_domain.get(e["domain"], 0) + 1

    print(f"Wrote {len(entries)} entries to {output_path}")
    print(f"  by complexity: {counts_by_complexity}")
    print(f"  by domain:     {counts_by_domain}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
